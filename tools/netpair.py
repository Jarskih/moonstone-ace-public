#!/usr/bin/env python3
"""ROADMAP 12.8b first light: two WinUAE windows play one co-op game over TCP (bsdsocket emulation on localhost).

  py tools/netpair.py [--build build-autoplay] [--host-instance 94] [--join-instance 95] [--port 6590] [--delay 2] [--net-timeout 60]
                      [--host-script tests/boot/net_pair_host.txt] [--join-script tests/boot/net_pair_join.txt] [--timeout 900]
                      [--join-wait 20] [--speed real|max|warp] [--lobby HOST] [--dashboard URL] [--resolve HOST:PORT:IP] [--poll 15] [--tail 45] [--tcp] [--no-run]
  py tools/netpair.py --relay [--lobby-port 6511] [...]     the relay run (ROADMAP 12.13a / 12.18), below
  py tools/netpair.py --ending [...]                        a game played to the ending (tests/boot/net_end_*.txt), below
  py tools/netpair.py --quad [...]                          4-player co-op: four windows (--players 4), tests/boot/net_quad_host.txt + net_quad_join1..3.txt
  py tools/netpair.py --classic [...]                       a classic game for two (tests/boot/net_classic_host.txt / net_classic_join.txt)

Takes ONE MS_AUTOPLAY build (default build-autoplay/, `cmake --build build-autoplay && cmake --build build-autoplay --target hdinstall`),
copies its hd/ tree twice (hd-<instance>), writes each copy's startup-sequence (LF only) with the net arguments

    host:  moonstone HOST PORT <port> NAME HOST DELAY <d> TIMEOUT <t>
    join:  moonstone JOIN 127.0.0.1 PORT <port> NAME GUEST DELAY <d> TIMEOUT <t>

(HOST / JOIN only pre-fill the Multiplayer screen; the scripts drive it), writes a WinUAE config per instance (bsdsocket_emu=true) and starts
uaeshot.ps1 -Instance for both, each with its own autoplay script.  The join window starts --join-wait seconds later so the host listens first.
When both are done it reads build/uaeshot-<instance>.log of each window and compares the logged state hashes:

    net: hash tick N crc XXXXXXXX     (every 50 ticks, both nodes, the same tick)
    net: desync at tick N ...         (the session ended on a mismatch; the field dumps "net: dump ..." follow)

--lobby HOST writes `lobby = HOST` into the host window's net.ini (for a PC whose DNS does not resolve the built-in lobby name: an IP works).
--dashboard URL (default the public dashboard's /api/games) is polled with curl every --poll seconds while the windows run (--resolve passes
curl's --resolve HOST:PORT:IP, default the owner's server); every change of the answer is printed with the time since the start and the whole
series goes to build/netpair-dashboard.log.  --dashboard '' switches it off.  --tail N keeps polling N seconds after both windows
quit (the host's listing must have gone by then).

--relay (ROADMAP 12.13a game side + 12.18): the host's game is listed VIA RELAY and the guest finds it in the game browser.  netpair starts a LOCAL lobby
server (`py -m tools.netserver --bind 127.0.0.1 --port <lobby-port> --no-connect-back --http-port <lobby-port + 1>`, the public server is never touched),
whose connect-back test always fails, so the host's REGISTER is answered "relay" and the host keeps an idle relay connection there; both windows get
`lobby = 127.0.0.1` / `lobby_port = <n>` in their net.ini.  The host window starts first; the join window starts when the host's log says `lobby status 3`
(listed via relay) and `relay state 4` (the idle connection is up), without a JOIN address: its script (tests/boot/net_relay_join.txt) opens FIND GAME
(`poke netaction 4`), waits for the list with the host's game, joins it with fire - JOIN_REQ, JOIN_REPLY relay, a connection to the lobby with RELAY_HELLO -
and from the lobby on both scripts are the direct run's (tests/boot/net_relay_host.txt / net_relay_join.txt are generated by tests/boot/src/mknetpair.py).
Extra PASS conditions: the host's log has `relay client arrived`, the join log `join via relay`, and the local server's dashboard showed the game with
connection "Relay".  The dashboard polled in this mode is the local one (--dashboard / --resolve are ignored).

--ending (NETPLAY.md 4.6, tests/boot/net_end_host.txt / net_end_join.txt, generated by tests/boot/src/mknetpair.py): a normal two-player game is played to the
ending.  Tick-pokes (docs/AUTOPLAY.md) put all four moonstones and the party on Stonehenge at the same tick on both windows (the hashes behind them must
match), the leader's fire enters Stonehenge, the ending runs on both windows OUTSIDE the lockstep, the session closes by itself and the main menu comes back.
Shots are netend-h-* / netend-j-*.  Extra PASS conditions: both logs have `net: the quest is complete` and, after the ending, `net: session closed after the
ending` and the overlay switch back to mog; no state hash follows the quest; the host's listing was removed (`net: lobby: unlisted`); the last common hash is
behind the last tick-poke; both windows applied the same tick-pokes at the same ticks.  Automatic when a script is named net_end_*.

--players N (2..4, default 2; --quad = 4): the host (instance --host-instance, 94) plus N-1 join windows (instances --join-instance .., 95/96/97, each with its own
hd-<instance> copy, NAME GUEST1..GUEST3 for N > 2, JOIN 127.0.0.1).  The first joiner starts --join-wait seconds after the host; each next one when the host's log
says the previous joiner is seated (`net: peers K`; --stagger fixed: --join-wait seconds later) - the lobby gives the seats, and so the portraits, in start order.
All windows run under the one emulator lock; the net timeout is 120 s with more than 2 windows.  --join-scripts a b c names the join scripts (default net_quad_join1..3).
PASS for N windows: every window quits, at least one tick was hashed by ALL windows, every such tick has one crc in all windows, the tick-pokes agree, no BAD line; the
summary prints `tick N host XXXXXXXX join1 XXXXXXXX ...` per common tick.  --classic: MODE is switched to CLASSIC in the lobby (NETPLAY.md 4.2b), each knight has its own turn.
(--relay and --ending are two-window runs.)

UDP (ROADMAP 12.21, NETPLAY.md 2.2): the per-tick traffic travels as datagrams with redundant history once the probe handshake worked, in the direct run and through the
relay.  Extra PASS conditions: both logs have `net: udp: ok` and no `net: udp: fallback to tcp`; the session summary lines (`net: udp: session: sent N received M covered
C escalated E ...`) are printed.  --tcp starts both windows with the command line's TCP (the per-tick traffic stays on TCP: the A/B run) and expects the opposite:
`net: udp: fallback to tcp (disabled)` on both and no `net: udp: ok`.

Both windows run under the machine-wide emulator lock (tools/emulock.py: a second emulator job waits), at real speed unless --speed says otherwise.

Exit code 0 = both windows reached `quit`, at least one hash was compared and every common tick has equal hashes and no desync/timeout
line.  Shots land in build/shots/ (netpair-h-* from the host window, netpair-j-* from the join window).  --no-run only prepares the trees and
configs (and prints the commands) - the single real run is the main session's.
"""
import argparse
import os
import re
import shutil
import socket
import subprocess
import sys
import threading
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HASH = re.compile(r'net: hash tick (\d+) crc ([0-9A-Fa-f]{8})')
HASH_CUT = re.compile(r'net: hash tick \d+ crc\s*$')   # a hash line the serial capture cut before its value
BAD = re.compile(r'net: (desync|session ended|no session|session did not start)|net: rejoin: (failed|the session could not|nobody could be taken back|this machine.s world differs|the world does not fit)|NO quit line|SHOT-LATE|wait-timeout|AUTOPLAY ERROR|AUTOPLAY tick-poke .* FAILED', re.I)
TICKPOKE = re.compile(r'AUTOPLAY tick-poke (\S+) (\d+) at tick (\d+)')   # a script's `tick N poke ...` applied (docs/AUTOPLAY.md "Tick-aligned pokes")


def config(hd):
    """The default A1200 config of the repo with 4 MB fast RAM (the Debug exe needs it) and the bsdsocket emulation on."""
    src = open(os.path.join(ROOT, 'moonstone-ace-hd.uae'), encoding='ascii', errors='replace').read()
    src = re.sub(r'(?m)^fastmem_size=.*$', 'fastmem_size=4', src)
    if 'bsdsocket_emu' not in src:
        src += '\nbsdsocket_emu=true\n'
    else:
        src = re.sub(r'(?m)^bsdsocket_emu=.*$', 'bsdsocket_emu=true', src)
    return re.sub(r'(?m)^filesystem2=rw,DH0:hd:.*$', lambda m: 'filesystem2=rw,DH0:hd:' + hd + ',0', src)


def prepare(bdir, instance, args_line, lobby=None, lobby_port=0):
    """Copy <bdir>/hd to hd-<instance>, write its startup-sequence and the .uae; -> the config path (relative to ROOT)."""
    hd = os.path.join(bdir, 'hd-%d' % instance)
    # A fresh copy every run: a hd-<instance> left by an earlier run keeps its saved files (mods/options.ini, saves), and windows whose game data differ
    # refuse each other's HELLO (the first 4-window run: windows 94/95 reused old trees, 96/97 were new, so the third and fourth player were refused).
    shutil.rmtree(hd, ignore_errors=True)
    shutil.copytree(os.path.join(bdir, 'hd'), hd)
    with open(os.path.join(hd, 's', 'startup-sequence'), 'wb') as f:   # LF only: AmigaOS breaks on CRLF
        f.write(('moonstone ' + args_line + '\n').encode('ascii'))
    ini = os.path.join(hd, 'net.ini')
    if lobby:
        with open(ini, 'w', newline=chr(10)) as f:   # the lobby override (net.ini `lobby`); the game keeps unknown keys when it saves
            f.write('[net]' + chr(10) + 'lobby = %s' % lobby + chr(10) + ('lobby_port = %d' % lobby_port + chr(10) if lobby_port else ''))
    elif os.path.exists(ini):
        os.remove(ini)   # no stale name / address / public flag of an earlier run
    cfg = os.path.join(bdir, 'netpair-%d.uae' % instance)
    with open(cfg, 'w', encoding='ascii', newline='') as f:
        f.write(config(hd))
    return os.path.relpath(cfg, ROOT)


def command(cfg, instance, script, shots, timeout):
    return ['powershell', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', os.path.join(ROOT, 'uaeshot.ps1'), '-Config', cfg,
            '-Instance', str(instance), '-Autoplay', os.path.join(ROOT, script), '-Dir', shots, '-Timeout', str(timeout)]


class Dashboard(threading.Thread):
    """Polls the public dashboard's game list while the windows run (what the host's listing looks like from outside)."""

    def __init__(self, url, resolve, every):
        super().__init__(daemon=True)
        self.url, self.resolve, self.every = url, resolve, every
        self.stop = threading.Event()
        self.t0 = time.time()
        self.series = []

    def run(self):
        last = None
        while not self.stop.is_set():
            cmd = ['curl', '-s', '-m', '10']
            if self.resolve:
                cmd += ['--resolve', self.resolve]
            cmd.append(self.url)
            try:
                txt = subprocess.run(cmd, capture_output=True, text=True, timeout=20).stdout.strip()
            except (OSError, subprocess.SubprocessError) as e:
                txt = 'curl failed: %s' % e
            line = '+%4ds %s' % (time.time() - self.t0, txt or '(empty answer)')
            self.series.append(line)
            if txt != last:
                print('DASHBOARD', line, flush=True)
                last = txt
            self.stop.wait(self.every)

    def finish(self):
        self.stop.set()
        self.join(timeout=25)
        with open(os.path.join(ROOT, 'build', 'netpair-dashboard.log'), 'w', encoding='utf-8') as f:
            f.write(chr(10).join(self.series) + chr(10))


def wait_for_log(instance, patterns, timeout, poll=1.0):
    """Polls build/uaeshot-<instance>.log (the serial capture, written while the window runs) until every regex of patterns has a matching line.  True/False."""
    end = time.time() + timeout
    while time.time() < end:
        text = '\n'.join(read_log(instance))
        if all(re.search(p, text) for p in patterns):
            return True
        time.sleep(poll)
    return False


def port_open(port, timeout=10.0):
    end = time.time() + timeout
    while time.time() < end:
        try:
            socket.create_connection(('127.0.0.1', port), timeout=1).close()
            return True
        except OSError:
            time.sleep(0.2)
    return False


def start_local_lobby(port):
    """The relay run's lobby server: this repository's tools/netserver on 127.0.0.1, the connect-back test always failing (so every game is listed via relay)."""
    log = open(os.path.join(ROOT, 'build', 'netpair-server.log'), 'w')
    cmd = [sys.executable, '-m', 'tools.netserver', '--bind', '127.0.0.1', '--port', str(port), '--no-connect-back',
           '--http-port', str(port + 1), '--http-bind', '127.0.0.1', '--verbose',
           '--refresh-timeout', '600']   # a loaded machine runs the emulated clock (the host's REFRESH every 30 s) slower than real time: 75 s of silence would drop the listing
    proc = subprocess.Popen(cmd, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    if not port_open(port):
        proc.terminate()
        sys.exit('netpair: the local lobby server did not come up on port %d (build/netpair-server.log)' % port)
    return proc


def read_log(instance):
    path = os.path.join(ROOT, 'build', 'uaeshot-%d.log' % instance)
    try:
        lines = open(path, encoding='latin-1').read().splitlines()
    except OSError:
        return []
    if sum(1 for l in lines if len(l) == 12) >= 20:
        # the host window's serial capture sometimes breaks every line after 12 characters: glue the pieces together again
        glued, buf = [], ''
        for l in lines:
            if len(l) == 12:
                buf += l
            else:
                glued.append(buf + l)
                buf = ''
        lines = glued + ([buf] if buf else [])
    # the capture can also break a line at any width under load (2026-10-12 relay run: `net: hash tick 3300 crc` / `DA17886D`): a hash line
    # without its value takes the next line's leading hex word
    fixed = []
    for l in lines:
        if fixed and HASH_CUT.search(fixed[-1]) and re.match(r'\s*[0-9A-Fa-f]{1,8}', l):
            fixed[-1] = fixed[-1].rstrip() + ' ' + l.strip()
        else:
            fixed.append(l)
    return fixed


def hashes(lines):
    return {int(m.group(1)): m.group(2).upper() for m in (HASH.search(l) for l in lines) if m}


def relay_checks(host_lines, join_lines, series):
    """The extra PASS conditions of --relay: the host got its client through the relay, the guest joined through it, the local lobby listed the game via relay."""
    out, ok = [], True
    for what, lines, pattern in (('host: a client arrived through the relay', host_lines, r'net: relay client arrived on link'),
                                 ('join: the game browser listed the host\'s game', join_lines, r'net: find status 2 games 1'),
                                 ('join: joined through the relay', join_lines, r'net: join via relay'),
                                 ('host: listed via relay', host_lines, r'net: lobby status 3 ')):
        found = any(re.search(pattern, l) for l in lines)
        ok &= found
        out.append('  %s: %s' % (what, 'yes' if found else 'NO'))
    via_relay = any('Relay' in l for l in series)
    ok &= via_relay
    out.append('  local lobby dashboard showed the game with connection Relay: %s' % ('yes' if via_relay else 'NO'))
    return ok, out


def udp_checks(host_lines, join_lines, is_tcp_only):
    """The UDP conditions (ROADMAP 12.21): both nodes completed the probe handshake and nobody fell back; with --tcp the opposite."""
    out, ok = [], True
    for name, lines in (('host', host_lines), ('join', join_lines)):
        has_ok = any('net: udp: ok' in l for l in lines)
        fell = [l.strip() for l in lines if 'net: udp: fallback to tcp' in l]
        if is_tcp_only:
            good = not has_ok and any('fallback to tcp (disabled)' in l for l in fell)
            out.append('  %s: TCP forced, no UDP handshake: %s' % (name, 'yes' if good else 'NO'))
        else:
            good = has_ok and not fell
            out.append('  %s: net: udp: ok and no fallback: %s' % (name, 'yes' if good else 'NO'))
            for l in fell:
                out.append('    ' + l)
        ok &= good
        for l in lines:
            if 'net: udp: session:' in l:
                out.append('  %s: %s' % (name, l.strip()))
    return ok, out


def tick_pokes(lines):
    """[(variable, value, tick)] of the tick-pokes a window applied, in order."""
    return [m.groups() for m in (TICKPOKE.search(l) for l in lines) if m]


def ending_checks(host_lines, join_lines):
    """The extra PASS conditions of --ending (tests/boot/net_end_*.txt): a game played to the ending closes its session cleanly (NETPLAY.md 4.6).
    Both windows log the quest being complete and, after the ending, the closed session; no state hash follows the ending (it runs outside the
    lockstep); the host's listing was removed; the last hash both windows logged lies behind the tick-pokes (it covers the poked state)."""
    out, ok = [], True
    for name, lines in (('host', host_lines), ('join', join_lines)):
        text = [l for l in lines]
        idx = {}
        for key, pat in (('complete', 'net: the quest is complete'), ('closed', 'net: session closed after the ending'), ('mog', 'rtGameRun: enter mog')):
            idx[key] = max([i for i, l in enumerate(text) if pat in l] or [-1])
        last_hash = max([i for i, l in enumerate(text) if HASH.search(l)] or [-1])
        for what, good in (('the quest is complete (the session starts to close)', idx['complete'] >= 0),
                           ('the session closed after the ending', idx['closed'] > idx['complete'] >= 0),
                           ('the main menu came back (enter mog after the close)', idx['mog'] > idx['closed'] >= 0),
                           ('no state hash after the quest was complete', last_hash < idx['complete'])):
            ok &= good
            out.append('  %s: %s: %s' % (name, what, 'yes' if good else 'NO'))
    listed_gone = any('net: lobby: unlisted' in l for l in host_lines)
    ok &= listed_gone
    out.append('  host: the lobby listing was removed (net: lobby: unlisted): %s' % ('yes' if listed_gone else 'NO'))
    pokes = tick_pokes(host_lines)
    hh, jh = hashes(host_lines), hashes(join_lines)
    common = sorted(set(hh) & set(jh))
    covered = bool(pokes) and bool(common) and common[-1] > max(int(p[2]) for p in pokes)
    ok &= covered
    out.append('  the last common hash (tick %s) is behind the last tick-poke (tick %s): %s' % (common[-1] if common else '-', max([int(p[2]) for p in pokes] or [0]),
                                                                                          'yes' if covered else 'NO'))
    return ok, out


def compare(host_lines, join_lines):
    """-> (ok, report lines) for the two-window runs."""
    return compare_n([('host', host_lines), ('join', join_lines)])


def compare_n(windows):
    """windows = [(name, log lines)], the host first.  -> (ok, report lines).  PASS: every window reached `quit`, at least one tick was hashed by ALL windows,
    every such tick has the same crc in all of them, the tick-pokes agree, no BAD line.  Two windows print the format of the first netpair runs."""
    out, ok = [], True
    names = [n for n, _ in windows]
    hs = [hashes(lines) for _, lines in windows]
    common = sorted(set.intersection(*(set(h) for h in hs))) if hs else []
    out.append('hashes: ' + ', '.join('%s %d' % (n, len(h)) for n, h in zip(names, hs)) + ', common %d' % len(common))
    for t in common:
        same = len(set(h[t] for h in hs)) == 1
        ok &= same
        out.append('  tick %-6d ' % t + ' '.join('%s %s' % (n, h[t]) for n, h in zip(names, hs)) + (' ok' if same else ' MISMATCH'))
    if not common:
        ok = False
        out.append('  no tick was hashed on all windows' if len(windows) > 2 else '  no tick was hashed on both windows')
    sigs = {}
    for name, lines in windows:   # every window must present the same build / data / rules in its HELLO, or the host refuses the odd one (the lobby logs why)
        for l in lines:
            m = re.search(r'net: build (\w+) data (\w+) rules (\d+)', l)
            if m:
                sigs.setdefault(m.groups(), []).append(name)
                break
    if len(sigs) > 1:
        ok = False
        out.append('windows differ in build / data / rules (the host refuses the odd one): ' + '; '.join('%s = build %s data %s rules %s' % (','.join(v), *k) for k, v in sigs.items()))
    pokes = [tick_pokes(lines) for _, lines in windows]
    if any(pokes):   # tick-pokes must have happened at the same ticks, with the same values, in the same order on every window
        same = all(p == pokes[0] for p in pokes)
        out.append('tick-pokes: ' + ', '.join('%s %d' % (n, len(p)) for n, p in zip(names, pokes)) + ('' if same else ' DIFFER'))
        for row in zip(*pokes):
            ok_row = all(r == row[0] for r in row)
            out.append('  %s %s: ' % (row[0][0], row[0][1]) + ' '.join('%s tick %s' % (n, r[2]) for n, r in zip(names, row)) + ('' if ok_row else ' MISMATCH'))
        ok &= same
    for name, lines in windows:
        if not any('AUTOPLAY quit' in l for l in lines):
            ok = False
            out.append('%s: no "AUTOPLAY quit" line (the script did not finish)' % name)
        quit_at = max([i for i, l in enumerate(lines) if 'AUTOPLAY quit' in l] or [-1])
        has_timeout = any('wait-timeout' in l for l in lines)
        for i, l in enumerate(lines):
            if BAD.search(l):
                # the peer that quits first ends the session of the other one a moment before its own quit: not an error
                if 'session ended' in l and 'desync' not in l and i < quit_at and not has_timeout:
                    out.append('%s: (tolerated, the peer left before this window quit) %s' % (name, l.strip()))
                    continue
                ok = False
                out.append('%s: %s' % (name, l.strip()))
    return ok, out


